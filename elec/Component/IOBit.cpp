//---------------------------------------------------------------------------
#include <vcl.h>
#pragma hdrstop

#include "IOBit.h"
#include <assert.h>

//---------------------------------------------------------------------------
#pragma package(smart_init)
//---------------------------------------------------------------------------
//  建構子
//---------------------------------------------------------------------------
IOBit::IOBit(int iNo,int iBNo,bool Read)
{
    IOByteObj = new IOByte(iNo,Read);

    assert(iBNo >= 0 && iBNo <= 0x80);
    BitNo = (byte) iBNo;
}

//---------------------------------------------------------------------------
//  解構子
//---------------------------------------------------------------------------
IOBit::~IOBit()
{
    delete IOByteObj;
}

//---------------------------------------------------------------------------
//  送出位元資料
//---------------------------------------------------------------------------
void IOBit::Out(bool Value)
{
    byte    PortValue = IOByteObj->In();

    if (Value) {                                    // 如果要打開
        PortValue |= BitNo;                         // 加上該BIT
    }
    else {                                              // 如果要關閉
        PortValue = byte(PortValue & (0xFF ^ BitNo));   // 取消該BIT
    }
    IOByteObj->Out(PortValue);
}

//---------------------------------------------------------------------------
//  讀回位元資料
//---------------------------------------------------------------------------
bool IOBit::In()
{
    return (IOByteObj->In() & BitNo) == BitNo;
}

 